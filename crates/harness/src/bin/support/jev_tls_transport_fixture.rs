//! A real certificate chain for the offline verification tests.
//!
//! These are a self-signed test CA and one leaf it signed for `api.typesafe.ai`, generated once
//! with OpenSSL and committed as DER. They exist so the offline suite can prove that verification
//! actually refuses, rather than only asserting that a configuration object was constructed.
//!
//! The private keys are deliberately not committed. The CA is in neither the pinned root store nor
//! anything a run trusts: it is a test fixture that happens to be spelled in DER. The leaf names
//! the admitted host, so presenting it to the real verifier is the substitution this lane exists
//! to refuse -- a well-formed chain for the right name, signed by nothing that vouches for it.
//!
//! Reproduce with:
//!
//! ```text
//! openssl req -x509 -newkey rsa:2048 -keyout ca.key -out ca.crt -days 3650 -nodes \
//!   -subj "/CN=h299 offline test CA"
//! openssl req -newkey rsa:2048 -keyout leaf.key -out leaf.csr -nodes -subj "/CN=api.typesafe.ai"
//! printf "subjectAltName=DNS:api.typesafe.ai\nbasicConstraints=CA:FALSE\nextendedKeyUsage=serverAuth\n" > leaf.ext
//! openssl x509 -req -in leaf.csr -CA ca.crt -CAkey ca.key -CAcreateserial -out leaf.crt -days 3650 -extfile leaf.ext
//! ```

