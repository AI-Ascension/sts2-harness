//! A loopback TLS peer for the offline handshake tests.
//!
//! A second fixture CA and leaf, this time with the private key committed alongside them, because a
//! peer has to be able to complete a handshake to prove that the client side can drive one. The
//! [`tls_fixture`] material deliberately has no key: it exists to prove a chain that nothing
//! vouches for is refused, and a key would turn that into a peer rather than a negative case.
//!
//! This key is a test fixture for a CA that is in no trust store any run consults. It is generated
//! once and committed so the suite stays hermetic: the tests that need a live handshake need a
//! peer, and deriving one at run time would make the handshake's correctness depend on the host's
//! `openssl` and on a keygen call. Committing a key that vouches for nothing is the smaller risk,
//! and it is scoped to `cfg(test)` so it is not linked into the bridge binary a run executes.
//!
//! Reproduce with:
//!
//! ```text
//! openssl ecparam -name prime256v1 -genkey -noout -out ca.key
//! openssl req -x509 -new -key ca.key -sha256 -days 3650 -out ca.crt \
//!   -subj "/CN=h299 loopback test CA" -addext "basicConstraints=critical,CA:TRUE"
//! openssl ecparam -name prime256v1 -genkey -noout -out leaf.key
//! openssl req -new -key leaf.key -out leaf.csr -subj "/CN=api.typesafe.ai"
//! printf "subjectAltName=DNS:api.typesafe.ai\nbasicConstraints=CA:FALSE\nextendedKeyUsage=serverAuth\nkeyUsage=digitalSignature,keyAgreement\n" > leaf.ext
//! openssl x509 -req -in leaf.csr -CA ca.crt -CAkey ca.key -CAcreateserial \
//!   -out leaf.crt -days 3650 -sha256 -extfile leaf.ext
//! ```
//!
//! `prime256v1` rather than `rsa:2048` on purpose: a `2048`-bit RSA key is below the floor webpki
//! enforces, so such a leaf would be refused for its key size and the loopback tests would assert
//! nothing about the handshake loop itself.

